# Fan-out device test (the 24Ai copy-64 fault): route each AVB input
# stream j of a MOTU to its output j AND to outputs j+nin, j+2*nin, ... and
# receive all its outputs.  The copies carry the same source data at the same
# time, so a fault event shows where the data goes bad:
#   on all copies at once  -> before the split: input side / router
#   on one copy only       -> after the split: that output stream
#
#   ./tests/motu/fanout.sh <host> apply   loopback pairs (as n4-<host>) + fan-out routing + our extra inputs
#   ./tests/motu/fanout.sh <host> check   read-only: routing and connections in place
#   SECS=1200 ./tests/motu/fanout.sh <host> run    check, then device_check.sh with the fan-out map
#   ./tests/motu/fanout.sh <host> undo    clear the fan-out routing, disconnect our extra inputs
#
# Needs the stack at N >= the device's output stream count, its stream 0 on
# the device:  sudo AVB_DEVICE_SOURCE_MAC=<device MAC> ./avb_up.sh <iface> 48000 --num-streams <nout>
# Every write goes through motu_ds.sh (snapshot first), so `motu_ds.sh restore`
# also undoes it.  For the 24Ai: nin 4, nout 8, in j -> out j and j+4.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
DS=$HERE/motu_ds.sh
LOGDIR=${LOGDIR:-/dev/shm}
PROCDIR=/proc/snd_igb_avb

say() { printf '\033[1m== %s\033[0m\n' "$*"; }
ok()  { printf '\033[32mok\033[0m   %s\n' "$*"; }
bad() { printf '\033[31mFAIL\033[0m %s\n' "$*"; }
die() { printf '!! %s\n' "$*" >&2; exit 2; }

[ $# -eq 2 ] || die "usage: $0 <host> apply|check|run|undo"
H=$1 CMD=$2
DSJ=$LOGDIR/fanout-$H.datastore.json
load() { curl -s -m 5 "http://$H/datastore" > "$DSJ" && [ -s "$DSJ" ] || die "$H does not answer"; }
load
EID=$(jq -r .uid "$DSJ")
NIN=$(jq -r --arg e "$EID" '[keys[] | select(test("^avb/\($e)/cfg/0/input_streams/[0-9]+/talker$"))] | length' "$DSJ")
NOUT=$(jq -r --arg e "$EID" '[keys[] | select(test("^avb/\($e)/cfg/0/output_streams/[0-9]+/num_ch$"))] | length' "$DSJ")
[ "$NIN" -gt 0 ] && [ "$NOUT" -gt "$NIN" ] || die "$H: $NIN AVB inputs, $NOUT outputs -- nothing to fan out"
# bank index of "AVB Stream <n>" (1-based, as the MOTU names them)
bank() { jq -r --arg io "$1" --arg n "AVB Stream $2" \
  'to_entries[] | select(.key | test("^ext/\($io)/[0-9]+/name$")) | select(.value == $n) | .key | split("/")[2]' "$DSJ"; }
NCH=8

# the loopback pairs, as a topology motu_ds.sh can apply / check
TOPOF=$LOGDIR/fanout-$H.topo
printf '# generated by fanout.sh: %s loopback pairs (the fan-out copies are extra)\n0-%d %s 0-%d\n' \
  "$H" $((NIN - 1)) "$H" $((NIN - 1)) > "$TOPOF"

# "<out> <in>" for every fan-out copy: out o (>= nin) <- in o mod nin
copies() { local o; for ((o = NIN; o < NOUT; o++)); do echo "$o $((o % NIN))"; done; }

want_route() { printf '"%s:%s"' "$(bank ibank $(($2 + 1)))" "$3"; }   # <out> <in> <ch>

case $CMD in
apply)
  N=$(grep -c '^stream_id=' "$PROCDIR/streams" 2>/dev/null) || die "stack not up"
  [ "$N" -ge "$NOUT" ] || die "stack N=$N < $NOUT outputs of $H: restart with --num-streams $NOUT"
  say "fan-out $H: $NIN inputs -> $NOUT outputs ($(copies | awk '{printf "%sin %d->out %d", s, $2, $1; s=", "}'))"
  EXTRA_STREAMS=$((NOUT - NIN)) "$DS" apply "$TOPOF" || die "apply of the loopback pairs failed"
  load
  while read -r o i; do
    ob=$(bank obank $((o + 1)))
    [ -n "$ob" ] || die "$H has no obank 'AVB Stream $((o + 1))'"
    for ((c = 0; c < NCH; c++)); do
      "$DS" set "$H" "ext/obank/$ob/ch/$c/src" "$(want_route "$o" "$i" "$c")" >/dev/null || die "routing write failed"
    done
    ok "$H AVB out $((o + 1)) <- AVB in $((i + 1)) (obank $ob)"
  done < <(copies)
  while read -r o i; do
    "$DS" connect "$H" us "$o" "$H" "$o" | tail -1
  done < <(copies)
  "$0" "$H" check
  ;;
check)
  rc=0
  # the stack runs the copies as extra streams on top of the topology's pairs
  if out=$(EXTRA_STREAMS=$((NOUT - NIN)) "$DS" check "$TOPOF" 2>&1); then
    ok "loopback pairs ($NIN) + stack N=$NOUT"
  else
    grep -iv '== check' <<< "$out" | grep -i fail; rc=1
  fi
  US=$(jq -r 'to_entries[] | select(.key | test("^avb/[0-9a-f]+/model_name$")) | select(.value == "Linux AVB") | .key | split("/")[1]' "$DSJ" | head -1)
  [ -n "$US" ] || { bad "our entity is not in $H's datastore"; rc=1; }
  while read -r o i; do
    ob=$(bank obank $((o + 1)))
    for ((c = 0; c < NCH; c++)); do
      got=$(jq -c --arg k "ext/obank/$ob/ch/$c/src" '.[$k]' "$DSJ")
      [ "$got" = "$(want_route "$o" "$i" "$c")" ] || { bad "$H AVB out $((o + 1)) ch $c src $got (want $(want_route "$o" "$i" "$c"))"; rc=1; }
    done
    got=$(jq -r --arg k "avb/$US/cfg/0/input_streams/$o/talker" '.[$k] // ""' "$DSJ")
    [ "$got" = "$EID:$o" ] || { bad "our input $o <- '$got' (want $EID:$o)"; rc=1; }
  done < <(copies)
  [ $rc = 0 ] && ok "fan-out $H in place: $NIN loopback pairs + $((NOUT - NIN)) copies"
  exit $rc
  ;;
run)
  "$0" "$H" check || die "fan-out not in place: $0 $H apply"
  CHECK=0 MAP="0-$((NOUT - 1))=$H:0" SRC=$(copies | awk '{ printf "%s%s=%s", s, $1, $2; s = "," }') \
    exec "$HERE/device_check.sh" "$TOPOF" "$H"
  ;;
undo)
  while read -r o i; do
    ob=$(bank obank $((o + 1)))
    for ((c = 0; c < NCH; c++)); do "$DS" set "$H" "ext/obank/$ob/ch/$c/src" '""' >/dev/null; done
    ok "$H AVB out $((o + 1)) routing cleared"
    "$DS" connect "$H" us "$o" 0000000000000000 0 | tail -1
  done < <(copies)
  ;;
*) die "unknown command $CMD (apply|check|run|undo)" ;;
esac
